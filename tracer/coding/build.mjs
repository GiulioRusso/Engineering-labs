// Regenerates traces/<id>.js and views/catalog.js for the coding subject: every program in four languages,
// run once per input by its JavaScript twin. Usage: node tracer/coding/build.mjs (then npm run build).
import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tracer, parseSource, LANGS } from './tracer.mjs';
import basics from './programs-basics.mjs';
import data from './programs-data.mjs';
import { FLOWS } from './flows.mjs';

export const PROGRAMS = [...basics, ...data];

export function traceOf(P) {
  const sources = Object.fromEntries(LANGS.map((l) => [l, parseSource(P.src[l])]));
  const inputs = P.inputs.map((inp) => { const t = tracer(inp.args); P.run(t); return { label: inp.label, args: inp.args, steps: t.steps }; });
  return { id: P.id, name: P.name, chapter: P.chapter, complexity: { time: '?', space: '?' }, view: 'program', panels: [], flow: FLOWS[P.id] || null, displaySource: sources.python.lines, lineMap: sources.python.map, sources, inputs };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dir = dirname(fileURLToPath(import.meta.url));
  mkdirSync(join(dir, 'traces'), { recursive: true });
  for (const P of PROGRAMS) {
    const T = traceOf(P);
    writeFileSync(join(dir, 'traces', `${P.id}.js`), `// Generated by build.mjs from programs-*.mjs - do not edit by hand.\nwindow.TRACES = window.TRACES || {};\nwindow.TRACES[${JSON.stringify(P.id)}] = ${JSON.stringify(T)};\n`);
  }
  const chapters = [...new Set(PROGRAMS.map((p) => p.chapter))];
  writeFileSync(join(dir, 'views', 'catalog.js'), `// Generated by build.mjs - one entry per program (chapters become the sidebar groups).\nwindow.CATALOG = ${JSON.stringify(chapters.map((c) => ({ chapter: c, items: PROGRAMS.filter((p) => p.chapter === c).map((p) => ({ id: p.id, name: p.name, what: p.what })) })), null, 1)};\n`);
  console.log(`built ${PROGRAMS.length} program(s)`);
}
