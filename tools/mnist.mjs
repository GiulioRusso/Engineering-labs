// Builds src/deep-learning/data/mnist.js: a small, balanced MNIST subset for the deep-learning labs.
// Usage: node tools/mnist.mjs <dir with the four original .gz files>
// Keeps the first 300 training and 100 test images of each digit, averages 2×2 blocks (28×28 → 14×14),
// stores 4 bits per pixel, two pixels per byte, base64. MNIST: Y. LeCun, C. Cortes, C. J. C. Burges,
// licensed CC BY-SA 3.0.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = process.argv[2], root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => gunzipSync(readFileSync(join(dir, f)));
function pick(images, labels, perDigit) {
  const img = read(images), lab = read(labels), n = lab.readUInt32BE(4), want = new Array(10).fill(perDigit), x = [], y = [];
  for (let i = 0; i < n && want.some((w) => w); i++) {
    const d = lab[8 + i]; if (!want[d]) continue; want[d]--;
    const px = new Uint8Array(98); // 196 pixels at 4 bits
    for (let r = 0; r < 14; r++) for (let c = 0; c < 14; c++) {
      let s = 0; for (const [dr, dc] of [[0, 0], [0, 1], [1, 0], [1, 1]]) s += img[16 + i * 784 + (2 * r + dr) * 28 + 2 * c + dc];
      const q = Math.round(s / 4 / 17), k = r * 14 + c; px[k >> 1] |= k & 1 ? q << 4 : q;
    }
    x.push(px); y.push(d);
  }
  return { x: Buffer.concat(x).toString('base64'), y: Buffer.from(y).toString('base64'), n: y.length };
}
const train = pick('train-images-idx3-ubyte.gz', 'train-labels-idx1-ubyte.gz', 300), test = pick('t10k-images-idx3-ubyte.gz', 't10k-labels-idx1-ubyte.gz', 100);
const out = join(root, 'src', 'deep-learning', 'data', 'mnist.js');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `// MNIST subset (generated by tools/mnist.mjs, do not edit): ${train.n} training and ${test.n} test digits,
// 14×14 pixels, 4 bits each. MNIST by Y. LeCun, C. Cortes and C. J. C. Burges, licensed CC BY-SA 3.0.
const TRAIN_X = '${train.x}';
const TRAIN_Y = '${train.y}';
const TEST_X = '${test.x}';
const TEST_Y = '${test.y}';
const bytes = (b64) => Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
// { x: Float32Array(n·196) in [0, 1], y: Uint8Array(n) }
function unpack(xs, ys) {
  const p = bytes(xs), y = bytes(ys), x = new Float32Array(y.length * 196);
  for (let k = 0; k < x.length; k++) x[k] = ((k & 1 ? p[k >> 1] >> 4 : p[k >> 1] & 15)) / 15;
  return { x, y, n: y.length };
}
let cache = null;
export const mnist = () => (cache ??= { train: unpack(TRAIN_X, TRAIN_Y), test: unpack(TEST_X, TEST_Y) });
export const SIDE = 14;
`);
console.log(`wrote ${out}: ${train.n} train, ${test.n} test`);
